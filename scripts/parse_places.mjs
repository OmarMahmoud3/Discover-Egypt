// Parse places
const blocks = rawText.split(/------------------------------------------------------------------------/);
const places = [];

let imgCounter = {};

for (const block of blocks) {
  const trimmed = block.trim();
  if (!trimmed || !trimmed.includes('المكان رقم')) continue;

  const getField = (label) => {
    const regex = new RegExp(`${label}:?\\s*(.*)`, 'i');
    const match = trimmed.match(regex);
    return match ? match[1].trim() : '';
  };

  const name = getField('الاسم بالعربية');
  const nameEn = getField('الاسم بالإنجليزية \\(اختياري\\)') || getField('الاسم بالإنجليزية');
  const slug = getField('المعرّف Slug');
  const cityRaw = getField('المدينة / المنطقة');
  const categoryRaw = getField('التصنيف').toLowerCase();
  const desc = getField('الوصف');
  const latStr = getField('خط العرض Latitude');
  const lonStr = getField('خط الطول Longitude');

  if (!name || !slug) continue;

  const lat = parseFloat(latStr) || 29.9792;
  const lon = parseFloat(lonStr) || 31.1342;

  // Primary city extraction
  const cityParts = cityRaw.split('،');
  const cityPrimary = cityParts[cityParts.length - 1].trim() || cityRaw;
  const citySub = cityParts.length > 1 ? cityParts[0].trim() : '';

  // Image selection
  imgCounter[categoryRaw] = (imgCounter[categoryRaw] || 0);
  const imgs = categoryImages[categoryRaw] || categoryImages.historical;
  const image = imgs[imgCounter[categoryRaw] % imgs.length];
  imgCounter[categoryRaw]++;

  const categoryAr = categoryArabicMap[categoryRaw] || 'آثار وتاريخ';
  const categoryEn = categoryEnglishMap[categoryRaw] || 'Monuments & History';

  places.push({
    id: slug,
    slug: slug,
    name: name,
    nameEn: nameEn || name,
    city: cityPrimary,
    cityEn: cityPrimary,
    cityKey: cityPrimary.toLowerCase(),
    citySub: citySub,
    locationShort: `${cityRaw} — مصر`,
    locationShortEn: `${cityRaw} — Egypt`,
    category: categoryAr,
    categoryKey: categoryRaw,
    categoryEn: categoryEn,
    description: desc,
    historicalText: desc,
    historicalTextEn: desc,
    rating: (4.6 + ((slug.length % 5) * 0.08)).toFixed(1),
    reviewCount: `${(1200 + (slug.length * 85)).toLocaleString()}`,
    coordinates: `${lat.toFixed(4)}° N, ${lon.toFixed(4)}° E`,
    latitude: lat,
    longitude: lon,
    mapsUrl: `https://maps.google.com/?q=${lat},${lon}`,
    image: image,
    gallery: [
      {
        title: name,
        titleEn: nameEn || name,
        badge: categoryAr,
        badgeEn: categoryEn,
        url: image,
        alt: `${name} - ${nameEn}`
      }
    ],
    is_published: true,
  });
}

